import puppeteer from 'puppeteer';
const browser = await puppeteer.launch({ headless: 'shell', args: ['--no-sandbox','--disable-setuid-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl','--ignore-gpu-blocklist','--disable-dev-shm-usage','--mute-audio'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.setViewport({ width: 1440, height: 900 });
await page.goto('http://127.0.0.1:4174/', { waitUntil: 'domcontentloaded' });
await sleep(2300);
await page.evaluate(() => Array.from(document.querySelectorAll('button')).find((b) => b.textContent?.trim() === 'Settings')?.click());
await sleep(900);
const sidebar = await page.evaluate(() => {
  const card = Array.from(document.querySelectorAll('button')).find((b) => /developer profile/i.test(b.textContent || ''));
  const r = card?.getBoundingClientRect();
  return { found: !!card, fontSize: card ? getComputedStyle(card.querySelector('span span') || card).fontSize : null, width: r ? Math.round(r.width) : null, inPanel: (() => { const nav = document.querySelector('nav'); const nr = nav?.getBoundingClientRect(); return !!(r && nr && r.bottom <= nr.bottom && r.top >= nr.top); })() };
});
await page.evaluate(() => Array.from(document.querySelectorAll('button')).find((b) => /^About/.test((b.textContent || '').trim()) && b.className.includes('w-full'))?.click());
await sleep(700);
await page.screenshot({ path: 'screenshots/14-settings-about.png' });
await page.evaluate(() => Array.from(document.querySelectorAll('button')).find((b) => /^About the developer$/i.test((b.textContent || '').trim()))?.click());
await sleep(800);
const aboutLinks = await page.evaluate(() => Array.from(document.querySelectorAll('a')).filter((a) => /asif4517|asif_xrk|asifsrk/i.test(a.getAttribute('href') || '')).map((a) => ({ href: a.getAttribute('href'), target: a.getAttribute('target'), rel: a.getAttribute('rel') })));
await page.screenshot({ path: 'screenshots/13-about-page.png' });
await page.evaluate(() => Array.from(document.querySelectorAll('header nav button')).find((b) => /how to play/i.test(b.textContent || ''))?.click());
await sleep(600);
const howto = await page.evaluate(() => /HOW TO HUNT AN APEX/i.test(document.body.innerText));
await page.evaluate(() => Array.from(document.querySelectorAll('header nav button')).find((b) => /garage/i.test(b.textContent || ''))?.click());
await sleep(600);
const garage = await page.evaluate(() => /THE GARAGE/i.test(document.body.innerText));
await page.evaluate(() => Array.from(document.querySelectorAll('header nav button')).find((b) => /circuits/i.test(b.textContent || ''))?.click());
await sleep(600);
const circuits = await page.evaluate(() => /CHOOSE YOUR LINE/i.test(document.body.innerText));
await page.evaluate(() => Array.from(document.querySelectorAll('button')).find((b) => (b.textContent || '').trim().toUpperCase() === 'RACE')?.click());
await sleep(3000);
const race = await page.evaluate(() => ({ engine: !!window.__NEON_RUSH__, hud: !!document.querySelector('.hud-layer') }));
console.log(JSON.stringify({ sidebar, aboutLinks, howto, garage, circuits, race, errors }, null, 2));
await page.close();
await Promise.race([browser.close(), sleep(4000)]);
process.exit(0);
