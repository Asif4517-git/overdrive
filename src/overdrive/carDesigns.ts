/**
 * Per-vehicle geometry specification.
 * Profile coordinates are in metres: [z (forward +), y (up +)].
 * The five reference designs are swift, city, fortuner, m3 and f296.
 * Every other model has its own distinct proportions and feature set.
 */
export interface CarDesign {
  length: number;
  width: number;
  height: number;
  wheelbase: number;
  wheelRadius: number;
  wheelWidth: number;
  track: number;
  lowerY: number;
  beltY: number;
  rearWheelZ: number;
  frontWheelZ: number;
  archRadius: number;
  /** Top silhouette from nose to tail. */
  top: [number, number][];
  cabin: {
    frontZ: number;
    rearZ: number;
    roofFrontZ: number;
    roofRearZ: number;
    roofY: number;
    width: number;
    roofTaper?: number;
  };
  glassFront: [number, number][];
  glassRear?: [number, number][];
  grille: "hex" | "chromeBar" | "slats" | "kidney" | "mesh" | "round";
  headlights: "swept" | "slim" | "led" | "round";
  taillights: "swept" | "slim" | "round" | "quad";
  wheelStyle: "multi5" | "multi10" | "twin5" | "offroad" | "turbine" | "centerlock";
  wheelColor: string;
  caliperColor: string;
  darkCladding?: boolean;
  features: {
    roofRails?: boolean;
    sideSteps?: boolean;
    spareWheel?: boolean;
    hoodScoop?: boolean;
    bigWing?: boolean;
    lipSpoiler?: boolean;
    quadExhaust?: boolean;
    twinExhaust?: boolean;
    diffuser?: boolean;
    splitter?: boolean;
    carbonRoof?: boolean;
    blackPillar?: boolean;
    chromeTrim?: boolean;
    hoodVents?: boolean;
    sideIntakes?: boolean;
    foglights?: boolean;
    antenna?: boolean;
    blackGrille?: boolean;
  };
  cockpit: { x: number; y: number; z: number };
  shadowLength: number;
}

